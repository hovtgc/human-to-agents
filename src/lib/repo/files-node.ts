  "import { SlackAdapter } from \"./slack.ts\";",
  "import { DiscordAdapter } from \"./discord.ts\";",
  "",
  "const adapters = { slack: SlackAdapter, discord: DiscordAdapter } as const;",
  "",
  "const { values } = parseArgs({",
